#!/usr/bin/env sh
# Creates `.env` for the staging stack with random secrets.
#
# Run this script on the staging server, in the deployment directory. The
# script refuses to overwrite an existing `.env`. It needs the domain and the
# certificate email to create the file; it reads them from the environment or
# from the second and third arguments.

set -eu
umask 077

target="${1:-.env}"

if [ -e "$target" ]; then
	echo "$target already exists; remove it to generate a new one" >&2
	exit 0
fi

# The domain and the email are not secrets, so the deploy script passes them as
# arguments. The environment wins.
domain="${RESTICHUB_DOMAIN:-${2:-}}"
acme_email="${RESTICHUB_ACME_EMAIL:-${3:-}}"
if [ -z "$domain" ] || [ -z "$acme_email" ]; then
	echo "set RESTICHUB_DOMAIN and RESTICHUB_ACME_EMAIL to create $target" >&2
	exit 1
fi

# 32 random bytes in standard base64. The key encryption key is decoded with the
# standard base64 engine and must hold 32 bytes, so the value keeps the padding.
random() {
	head -c 32 /dev/urandom | base64
}

# The key encryption key goes to a file that Docker mounts as a secret. The control plane user
# (uid 10001) must read it, and the control plane refuses a file that others can read.
kek_file="$(dirname "$target")/secrets/restichub_kek"
if [ -e "$kek_file" ]; then
	echo "$kek_file already exists; remove it to generate a new one" >&2
	exit 1
fi
mkdir -p "$(dirname "$kek_file")"
chmod 700 "$(dirname "$kek_file")"
random > "$kek_file"
chmod 400 "$kek_file"
if [ "$(id -u)" -eq 0 ]; then
	chown 10001:10001 "$kek_file"
else
	echo "run this command to give the control plane access: sudo chown 10001:10001 $kek_file" >&2
fi

cat > "$target" <<EOF
# The staging environment. Generated by bootstrap.sh. Do not commit this file.
POSTGRES_USER=restichub
POSTGRES_PASSWORD=$(random)
POSTGRES_DB=restichub
RESTICHUB_OWNER_PASSWORD=$(random)
RESTICHUB_RUNTIME_PASSWORD=$(random)
RESTICHUB_DOMAIN=$domain
RESTICHUB_ACME_EMAIL=$acme_email
RESTICHUB_IMAGE_TAG=edge
RESTICHUB_TENANCY_MODE=multi
RESTICHUB_TRUSTED_PROXIES=172.28.0.0/24
# Alerts and notification channels (ADR-0036). Remove the leading # to set a value.
# RESTICHUB_PUBLIC_ORIGIN=https://stage.example.com
# RESTICHUB_NOTIFICATIONS_LANGUAGE=en
# RESTICHUB_SMTP_HOST=smtp.example.com
# RESTICHUB_SMTP_PORT=587
# RESTICHUB_SMTP_SECURITY=starttls
# RESTICHUB_SMTP_USERNAME=<user>
# RESTICHUB_SMTP_PASSWORD=<password>
# RESTICHUB_SMTP_FROM=restichub@example.com
# RESTICHUB_WEBHOOK_ALLOW_HTTP=false
# RESTICHUB_WEBHOOK_ALLOW_NETWORKS=10.20.0.0/16
EOF

chmod 600 "$target"
echo "wrote $target"
