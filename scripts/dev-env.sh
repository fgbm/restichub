#!/usr/bin/env sh
# Creates `.env` with random development secrets for `compose.yaml`.
#
# The values are for a local cluster only. The script refuses to overwrite an existing `.env`.

set -eu
umask 077

target=".env"

if [ -e "$target" ]; then
	echo "$target already exists; remove it to generate a new one" >&2
	exit 1
fi

# 32 random bytes in standard base64. The key encryption key is decoded with the standard base64
# engine and must hold 32 bytes, so the value keeps the padding.
random() {
	head -c 32 /dev/urandom | base64
}

cat > "$target" <<EOF
# Local development environment. Generated by scripts/dev-env.sh. Do not commit this file.
POSTGRES_USER=restichub
POSTGRES_PASSWORD=$(random)
POSTGRES_DB=restichub
RESTICHUB_OWNER_PASSWORD=$(random)
RESTICHUB_RUNTIME_PASSWORD=$(random)
RESTICHUB_KEK=$(random)
EOF

echo "wrote $target"
